"""The sample pipelines in examples/, run end to end through the command line.

They use only the offline fixture provider, so they run anywhere without network access.
"""

import csv
import json
import shutil
from pathlib import Path
from typing import Any

import pytest

from geoproduct.cli import main, parse_params
from geoproduct.engine import load_spec_file
from geoproduct.errors import GeoProductError

EXAMPLES = Path(__file__).resolve().parents[3] / "examples"
PIPELINES = sorted((EXAMPLES / "pipelines").glob("*.yaml"))


class Cli:
    def __init__(self, tmp_path: Path, capsys: pytest.CaptureFixture[str]) -> None:
        self.workspace = tmp_path / "ws"
        self.capsys = capsys
        data = self.workspace / "data"
        data.mkdir(parents=True)
        self.csv = shutil.copy(EXAMPLES / "data" / "sample-facilities.csv", data)

    def __call__(self, *args: str) -> tuple[int, Any]:
        code = main(["--workspace", str(self.workspace), "--json", *args])
        out = self.capsys.readouterr().out
        return code, json.loads(out) if out.strip() else None

    def run(self, name: str, *params: str) -> dict[str, Any]:
        args = ["run", str(EXAMPLES / "pipelines" / f"{name}.yaml")]
        if name == "csv-enrich":
            args += ["--param", f"file={self.csv}"]
        for param in params:
            args += ["--param", param]
        code, record = self(*args)
        record["exit"] = code
        return record

    def stage_dir(self, record: dict[str, Any], stage_id: str) -> Path:
        return self.workspace / "runs" / record["run_id"] / "stages" / stage_id


@pytest.fixture
def cli(tmp_path: Path, capsys: pytest.CaptureFixture[str]) -> Cli:
    return Cli(tmp_path, capsys)


def statuses(record: dict[str, Any]) -> dict[str, str]:
    return {s["stage_id"]: s["status"] for s in record["stages"]}


def geojson(path: Path) -> dict[str, Any]:
    return json.loads(path.read_text(encoding="utf-8"))


@pytest.mark.parametrize("path", PIPELINES, ids=lambda p: p.stem)
def test_every_example_is_a_valid_plan(path: Path, cli: Cli) -> None:
    load_spec_file(path)
    code, plan = cli("plan", str(path))
    assert code == 0
    assert plan


def test_hospitals(cli: Cli) -> None:
    record = cli.run("hospitals")
    assert record["exit"] == 0
    assert record["status"] == "succeeded"
    data = geojson(cli.stage_dir(record, "geojson") / "hospitals.geojson")
    by_name = {f["properties"]["name"]: f["properties"] for f in data["features"]}
    assert set(by_name) == {
        "Sample General Hospital",
        "Northside Hospital",
        "Riverside Clinic",
        "Hilltop Clinic",
    }
    hospital = by_name["Sample General Hospital"]
    assert hospital["building_match"]["status"] == "exact"
    assert hospital["conflicts"][0]["field"] == "attributes.beds"
    assert by_name["Riverside Clinic"]["building_match"]["status"] == "ambiguous"
    assert by_name["Hilltop Clinic"]["building_match"]["status"] == "none"
    assert data["sources"]
    assert data["evidence"]
    report = (cli.stage_dir(record, "report") / "hospitals.md").read_text(encoding="utf-8")
    assert "Synthetic data generated by geoproduct-core" in report


def test_commercial_buildings(cli: Cli) -> None:
    record = cli.run("commercial-buildings")
    assert record["exit"] == 0
    with (cli.stage_dir(record, "csv") / "commercial-buildings.csv").open(
        encoding="utf-8-sig", newline=""
    ) as handle:
        listed = list(csv.DictReader(handle))
    rows = {row["name"]: row for row in listed}
    # Two sites sharing a website, 400 m apart: two records linked as one organisation.
    acme = [row for row in listed if row["name"] == "Acme Offices"]
    assert len(acme) == 2
    assert acme[0]["organisation_id"]
    assert acme[0]["organisation_id"] == acme[1]["organisation_id"]
    market = rows["Corner Market"]
    assert market["building_match"] == "exact"
    assert market["location_kind"] == "building_footprint"
    assert float(market["attributes.area_m2"]) == pytest.approx(4450, rel=0.02)
    assert market["attributes.within_district"] == '["North Quarter"]'
    cafe = rows["Greenleaf Cafe"]
    assert cafe["building_match"] == "approximate_point"
    assert cafe["attributes.area_m2"] == ""


def test_transport_gate_fails_then_resumes_with_a_new_parameter(cli: Cli) -> None:
    record = cli.run("transport", "max_stop_distance_m=5")
    assert record["exit"] == 1
    assert record["status"] == "failed"
    assert record["error"]["code"] == "quality_gate_failed"
    assert statuses(record)["csv"] == "pending"
    assert (cli.stage_dir(record, "report") / "transport-stops.md").is_file()

    code, resumed = cli("resume", record["run_id"], "--param", "max_stop_distance_m=30")
    assert code == 0
    assert resumed["status"] == "succeeded"
    stages = statuses(resumed)
    assert stages["stops"] == stages["scored"] == "skipped"
    assert stages["validation"] == stages["csv"] == "succeeded"
    report = json.loads(
        (cli.stage_dir(resumed, "validation") / "report.json").read_text(encoding="utf-8")
    )
    found = {(f["record_id"], f["severity"]) for f in report["findings"]}
    assert found == {("fixture:poi-14", "error"), ("fixture:poi-15", "warning")}


def test_csv_enrichment(cli: Cli) -> None:
    record = cli.run("csv-enrich")
    assert record["exit"] == 0
    rows_stage = next(s for s in record["stages"] if s["stage_id"] == "rows")
    assert rows_stage["counts"] == {"input": 10, "output": 9, "rejected": 1}
    with (cli.stage_dir(record, "csv") / "facilities-enriched.csv").open(
        encoding="utf-8-sig", newline=""
    ) as handle:
        rows = {row["id"]: row for row in csv.DictReader(handle)}
    assert "fac-007" not in rows  # merged into fac-001
    assert rows["fac-001"]["building"] == "fixture:b-110"
    assert rows["fac-004"]["status"] == "unresolved"
    assert "no confident result" in rows["fac-004"]["limitations"]
    assert rows["fac-010"]["name"] == "'@Home Care"
    assert rows["fac-010"]["attributes.phone"] == "+1 555 0109"
    report = json.loads(
        (cli.stage_dir(record, "validation") / "report.json").read_text(encoding="utf-8")
    )
    assert ("within_area", "fac-009") in {(f["check"], f["record_id"]) for f in report["findings"]}


def test_cli_errors_and_listing(cli: Cli, capsys: pytest.CaptureFixture[str]) -> None:
    code, stages = cli("stages")
    assert code == 0
    assert len(stages) == 18
    code, error = cli("run", str(EXAMPLES / "pipelines" / "hospitals.yaml"), "--param", "x=1")
    assert code == 1
    assert error["error"]["code"] == "invalid_input"
    code, error = cli("status", "run_00000000000000000000000000")
    assert code == 1
    assert main(["--workspace", str(cli.workspace), "stage", "export.csv"]) == 0
    assert "copy_to" in capsys.readouterr().out
    assert main(["--workspace", str(cli.workspace), "runs"]) == 0


def test_param_values_are_json_or_text() -> None:
    assert parse_params(['a={"bbox": [0, 0, 1, 1]}', "b=3", "c=plain text", "d="]) == {
        "a": {"bbox": [0, 0, 1, 1]},
        "b": 3,
        "c": "plain text",
        "d": "",
    }
    with pytest.raises(GeoProductError):
        parse_params(["novalue"])
